package com.aliyun.odps;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;

/**
 * Package-internal reader for the userinfo part of a proxy endpoint.
 *
 * <p>Rules, all of them chosen so that a password survives the endpoint string unchanged:
 *
 * <ul>
 *   <li>the authority is split at the <b>last</b> {@code '@'}: an {@code '@'} inside a password is
 *       legal as long as it is percent-encoded, and taking the last one keeps {@code user} free of
 *       password bytes when callers forget to encode it;
 *   <li>userinfo is split at the <b>first</b> {@code ':'}: everything after it is the password, so
 *       {@code pass:word} stays one password instead of being truncated;
 *   <li>percent-escapes are decoded exactly once, and a {@code '%'} that is not followed by two hex
 *       digits is kept literally (no exception, no silent truncation), which is the shape passwords
 *       generated by enterprise identity providers actually have;
 *   <li>no userinfo, or an empty username, yields no credential: endpoints that previous SDK
 *       versions accepted without credentials keep behaving exactly as they did.
 * </ul>
 */
final class ProxyCredentialParser {

  private ProxyCredentialParser() {
  }

  /**
   * @param rawUserInfo still-percent-encoded userinfo ({@code user[:pass]}), may be null
   * @return the credential, or null when there is nothing usable in it
   */
  static ProxyCredential fromRawUserInfo(String rawUserInfo) {
    if (rawUserInfo == null || rawUserInfo.isEmpty()) {
      return null;
    }
    String user;
    String password;
    int colon = rawUserInfo.indexOf(':');
    if (colon < 0) {
      user = rawUserInfo;
      password = "";
    } else {
      user = rawUserInfo.substring(0, colon);
      password = rawUserInfo.substring(colon + 1);
    }
    user = percentDecode(user);
    password = percentDecode(password);
    if (user.isEmpty()) {
      return null;
    }
    return new ProxyCredential(user, password);
  }

  /**
   * Decodes {@code %XX} sequences once, treating the decoded octets as UTF-8 (the charset
   * {@code ProxyCredential#proxyAuthorizationHeader()} puts the credential in).
   *
   * <p>Invalid escapes are left as written: a password such as {@code 100%off} must arrive at the
   * proxy as {@code 100%off}, not mangled and not rejected.
   */
  static String percentDecode(String value) {
    if (value.indexOf('%') < 0) {
      return value;
    }
    ByteArrayOutputStream octets = new ByteArrayOutputStream(value.length());
    int i = 0;
    while (i < value.length()) {
      char c = value.charAt(i);
      if (c == '%' && i + 2 < value.length()
          && isHex(value.charAt(i + 1)) && isHex(value.charAt(i + 2))) {
        octets.write(Character.digit(value.charAt(i + 1), 16) * 16
            + Character.digit(value.charAt(i + 2), 16));
        i += 3;
      } else {
        // Literal text: write it as UTF-8 so that non-ASCII and surrogate pairs survive the
        // octet round trip instead of being cut into single bytes.
        int cp = value.codePointAt(i);
        byte[] literal = new String(Character.toChars(cp)).getBytes(StandardCharsets.UTF_8);
        octets.write(literal, 0, literal.length);
        i += Character.charCount(cp);
      }
    }
    return new String(octets.toByteArray(), StandardCharsets.UTF_8);
  }

  private static boolean isHex(char c) {
    return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
  }
}
